// Per-setter per-month manager notes (setter_period_notes, migration
// 20260729160000) with the "Notes from June PR" carry-forward: alongside a
// month's numbers the PRIOR month's note is fetched for read-only display.
// Pre-migration (or for viewers without read RLS) the queries return no rows
// and saves surface an error toast — the surrounding tables degrade to an
// empty Notes column, nothing crashes.

import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { supabase } from "@/integrations/supabase/client";
import { toast } from "sonner";
import { useAuth } from "@/contexts/AuthContext";

export interface PeriodNote {
  setter_profile_id: string;
  period_month: string;
  note: string;
}

/** First of the month before a yyyy-MM-01 key. */
export const priorMonthKey = (monthKey: string): string => {
  const d = new Date(`${monthKey}T12:00:00`);
  const prior = new Date(d.getFullYear(), d.getMonth() - 1, 1);
  const m = String(prior.getMonth() + 1).padStart(2, "0");
  return `${prior.getFullYear()}-${m}-01`;
};

export function useSetterPeriodNotes(profileIds: string[], monthKey: string) {
  const queryClient = useQueryClient();
  const { user } = useAuth();
  const prior = priorMonthKey(monthKey);
  const idsKey = [...profileIds].sort().join(",");

  const notesQuery = useQuery({
    queryKey: ["setter-period-notes", monthKey, idsKey],
    queryFn: async (): Promise<PeriodNote[]> => {
      if (!profileIds.length) return [];
      // Table is newer than the generated types (types.ts is regenerated by
      // the owner); the house cast pattern applies until then.
      const { data, error } = await supabase
        // eslint-disable-next-line @typescript-eslint/no-explicit-any
        .from("setter_period_notes" as any)
        .select("setter_profile_id, period_month, note")
        .in("setter_profile_id", profileIds)
        .in("period_month", [monthKey, prior]);
      if (error) {
        // Pre-migration the table doesn't exist — degrade to no notes.
        console.error("setter_period_notes read failed", error);
        return [];
      }
      return (data || []) as unknown as PeriodNote[];
    },
    enabled: profileIds.length > 0,
  });

  const current = new Map<string, string>();
  const priorNotes = new Map<string, string>();
  for (const n of notesQuery.data || []) {
    if (n.period_month === monthKey) current.set(n.setter_profile_id, n.note);
    else priorNotes.set(n.setter_profile_id, n.note);
  }

  const saveNote = useMutation({
    mutationFn: async ({ profileId, note }: { profileId: string; note: string }) => {
      if (!user?.id) throw new Error("Not signed in");
      const row = {
        setter_profile_id: profileId,
        period_month: monthKey,
        note,
        author_user_id: user.id,
      };
      const { error } = await supabase
        // eslint-disable-next-line @typescript-eslint/no-explicit-any
        .from("setter_period_notes" as any)
        // eslint-disable-next-line @typescript-eslint/no-explicit-any
        .upsert(row as any, { onConflict: "setter_profile_id,period_month" });
      if (error) throw error;
    },
    onSuccess: () => {
      toast.success("Note saved");
      queryClient.invalidateQueries({ queryKey: ["setter-period-notes"] });
    },
    onError: (e: Error) => {
      console.error(e);
      toast.error("Could not save note");
    },
  });

  return { notesQuery, current, priorNotes, saveNote };
}
